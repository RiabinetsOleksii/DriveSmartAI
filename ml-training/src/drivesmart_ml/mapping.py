CLASS_MAPPING = {class_id: name for class_id, name in enumerate(GTSRB_CLASS_NAMES)}


def validate_class_mapping(mapping: dict[int, str] | None = None) -> None:
    candidate = CLASS_MAPPING if mapping is None else mapping
    if set(candidate) != set(range(43)):
        raise ValueError("class mapping must contain class IDs 0 through 42")
    if len(set(candidate.values())) != 43:
        raise ValueError("class names must be unique")
